"""把初赛前 100 名的分数录成 CSV 并算名次密度（2026-11-21）。

数据来源：用户提供的排行榜截图（4 张，rank 1–100）。
用途：判断"再前进 N 名需要多少分"，以及我们当前的风险缓冲。
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np
import pandas as pd

ROOT = r"E:\挑战赛"
OUT_CSV = os.path.join(ROOT, "04_新一轮", "初赛前100名_2026-11-21.csv")
OUT_MD = os.path.join(ROOT, "reports", "名次密度分析_2026-11-21.md")

# BOARD 每条为 (名次, 分数)；已脱敏，不含任何机构或个人标识
BOARD = [   # (名次, 分数) —— 已脱敏：不含学校与姓名
    (1, 82.19), (2, 81.96), (3, 81.30), (4, 81.15), (5, 81.15),
    (6, 81.14), (7, 81.08), (8, 80.93), (9, 80.93), (10, 80.93),
    (11, 80.93), (12, 80.93), (13, 80.93), (14, 80.92), (15, 80.92),
    (16, 80.92), (17, 80.92), (18, 80.92), (19, 80.92), (20, 80.92),
    (21, 80.92), (22, 80.16), (23, 80.09), (24, 79.92), (25, 79.89),
    (26, 79.89), (27, 79.83), (28, 79.80), (29, 79.76), (30, 79.74),
    (31, 79.67), (32, 79.66), (33, 79.65), (34, 79.62), (35, 79.61),
    (36, 79.53), (37, 79.41), (38, 79.37), (39, 79.35), (40, 79.27),
    (41, 79.21), (42, 79.11), (43, 79.11), (44, 79.00), (45, 78.97),
    (46, 78.96), (47, 78.95), (48, 78.91), (49, 78.88), (50, 78.82),
    (51, 78.82), (52, 78.80), (53, 78.79), (54, 78.78), (55, 78.77),
    (56, 78.77), (57, 78.77), (58, 78.76), (59, 78.74), (60, 78.74),
    (61, 78.73), (62, 78.72), (63, 78.71), (64, 78.71), (65, 78.69),
    (66, 78.69), (67, 78.69), (68, 78.68), (69, 78.68), (70, 78.68),
    (71, 78.67), (72, 78.67), (73, 78.66), (74, 78.65), (75, 78.63),
    (76, 78.63), (77, 78.61), (78, 78.61), (79, 78.59), (80, 78.58),
    (81, 78.58), (82, 78.58), (83, 78.57), (84, 78.56), (85, 78.54),
    (86, 78.51), (87, 78.51), (88, 78.51), (89, 78.50), (90, 78.49),
    (91, 78.48), (92, 78.48), (93, 78.47), (94, 78.46), (95, 78.44),
    (96, 78.43), (97, 78.42), (98, 78.42), (99, 78.42), (100, 78.41),
]
OURS = 78.51
OUR_RANK = 87          # 参考位（本地分析用，不对外披露）


def main() -> None:
    d = pd.DataFrame(BOARD, columns=["rank", "score"])
    d.to_csv(OUT_CSV, index=False, encoding="utf-8-sig")

    n_total = 328
    cut_rank = int(np.floor(n_total * 0.30))          # 98
    cut_score = float(d.loc[d["rank"] == cut_rank, "score"].iloc[0])
    our_row = d[d["rank"] == OUR_RANK].iloc[0]
    same = d[d.score == OURS]

    L = ["# 名次密度分析（2026-11-21，基于初赛前 100 名实测榜）", "",
         f"- 入围队伍 {n_total}，前 30% = 前 **{cut_rank}** 名",
         f"- 第 {cut_rank} 名分数 = **{cut_score}**",
         f"- 我们：第 **{int(our_row['rank'])}** 名、**{OURS}** 分（比切线高 "
         f"**{OURS - cut_score:+.2f}**）",
         f"- 同分（{OURS}）共 **{len(same)}** 队：第 "
         + "、".join(str(int(r)) for r in same["rank"]) + " 名",
         f"- 第 1 名 {d.score.max()}，与我们差 {d.score.max() - OURS:+.2f}", ""]

    # ---- 逐名次密度 ----
    L += ["## 一、局部密度（每 1 个名次需要多少分）", "",
          "| 区间 | 名次跨度 | 分数跨度 | 分/名次 |", "|---|---:|---:|---:|"]
    bands = [(1, 7), (8, 21), (22, 36), (37, 49), (50, 64), (65, 79), (80, 87),
             (88, 98), (99, 100)]
    for a, b in bands:
        sub = d[(d["rank"] >= a) & (d["rank"] <= b)]
        if len(sub) < 2:
            continue
        ds = float(sub.iloc[0]["score"] - sub.iloc[-1]["score"])
        per = ds / (len(sub) - 1) if len(sub) > 1 else float("nan")
        L.append(f"| {a}–{b} | {len(sub)} | {ds:.2f} | **{per:.4f}** |")

    # ---- 爬到某名次需要多少分 ----
    L += ["", "## 二、从参考位爬到某名次要多少分", "",
          "| 目标名次 | 该名分数 | 需要提升(分) | 折成 AUC | 手上有没有 |",
          "|---:|---:|---:|---:|---|"]
    have = {"类2 收缩 0.50": 0.00083, "（已否决）bagging": -0.0098}
    for target in (80, 70, 60, 50, 40, 30, 20, 10):
        s = float(d.loc[d["rank"] == target, "score"].iloc[0])
        need = s - OURS
        ok = "✅ 类 2 收缩够" if need <= 0.083 else "❌ 无"
        L.append(f"| {target} | {s:.2f} | {need:+.2f} | {need / 100:.5f} | {ok} |")

    # ---- 各候选折成名次 ----
    L += ["", "## 三、现有候选折成名次（用切线附近密度 0.0082 分/名次）", "",
          "| 候选 | AUC 增益 | 折成平台分 | 约等于名次 | 状态 |",
          "|---|---:|---:|---:|---|",
          "| 类 2 收缩 0.50 | +0.00083 | +0.083 | **≈ 10 名** | 可做，符号不确定 |",
          "| 折模型 bagging | −0.0098 | −0.98 | −120 名 | **已否决** |",
          "| 其余七个方向 | ≤ +0.0001 | ≈ 0 | ≈ 0 | 全部为负 |", "",
          "> 注：密度在切线上方不均匀。往上到 79.0 之前，约 0.008~0.02 分/名次；",
          "> 跨过 78.9→79.0 与 79.2→79.3 有两处断层，名次跳跃更快。", ""]

    # ---- 榜单结构观察 ----
    plateau = d[(d["score"] >= 80.92) & (d["score"] <= 80.93)]
    L += ["## 四、榜单结构（对策略有用）", "",
          f"- **80.92–80.93 有 {len(plateau)} 支队伍挤在同一分**（第 8–21 名）—— 说明这批人踩在同一个天花板",
          "- 78.41–78.82（第 50–100 名）是**最密集**的一段，我们就在这里面",
          "- 第 22 名 80.16 与第 21 名 80.92 之间有 0.76 的断层 → 头部与中部是两个世界",
          "", "## 五、结论", "",
          f"1. **缓冲 = {OURS - cut_score:+.2f} 分 ≈ 11 个名次**，任何 −0.09 分的回退都会掉出前 30%。",
          "2. **类 2 收缩约值 10 名**（+0.083 分），是唯一能算出来的正向杠杆。",
          "3. **要进前 50 需要 +0.31 分（+0.0031 AUC）** —— 是我们的 4 倍，现有手段做不到。",
          "4. 国赛换榜重赛，初赛名次只能当参考；守住前 30% 是现实目标。"]

    open(OUT_MD, "w", encoding="utf-8").write("\n".join(L))
    json.dump({"ours": OURS, "rank": int(our_row["rank"]), "cut_rank": cut_rank,
               "cut_score": cut_score, "board": [[int(r), float(sc)] for r, sc in BOARD]},
              open(os.path.join(ROOT, "reports", "leaderboard_2026-11-21.json"), "w",
                   encoding="utf-8"), ensure_ascii=False, indent=1)
    print("\n".join(L))
    print(f"\n  [wrote] {os.path.relpath(OUT_MD, ROOT)}")


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    main()
